LANGS = {"en": EN, "uk": UK}
# each language by its own name, as a person looking for theirs reads it
NATIVE = {"en": "English", "uk": "Українська"}


def system_lang():
    """Ukrainian when Windows shows Ukrainian (primary language 0x22), English otherwise."""
    return "uk" if ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0x3FF == 0x22 else "en"


class Lang(QObject):
    """The language in use, for QML (L.qml) and for Python's own texts."""

    changed = Signal()

    def __init__(self):
        super().__init__()
        self.code = "en"

    def set(self, code):
        code = code if code in LANGS else system_lang()
        if code != self.code:
            self.code = code
            self.changed.emit()

    @Property(str, notify=changed)
    def lang(self):
        return self.code

    @Property("QVariantMap", notify=changed)
    def t(self):
        return LANGS[self.code]

    @Property("QVariantList", constant=True)
    def languages(self):
        return [{"code": c, "name": NATIVE[c]} for c in LANGS]


lang = Lang()


def tr(key, *args):
    s = LANGS[lang.code][key]
    for i, a in enumerate(args, 1):
        s = s.replace(f"%{i}", str(a))
    return s


def dec(text):
    """A number already formatted with a decimal point, in the language's way of writing it."""
    return text.replace(".", tr("dec"))
